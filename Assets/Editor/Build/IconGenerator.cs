#if UNITY_EDITOR
using System.IO;
using UnityEditor;
using UnityEngine;

namespace LoneFighter.EditorTools.Build
{
    /// Generates a 1024x1024 procedural app icon and assigns it to iOS PlayerSettings.
    /// Menu: LoneFighter > Build > Generate App Icon
    ///
    /// Style: dark gradient backdrop + neon player silhouette + radial bloom, consistent with
    /// the in-game palette. Apple wants a square 1024x1024 PNG with NO transparency and NO
    /// rounded corners (iOS rounds them automatically). All other sizes (180, 167, 152, 120,
    /// 87, 80, 76, 60, 58, 40, 29, 20) are generated by Unity from this marketing icon.
    public static class IconGenerator
    {
        const int Size = 1024;
        const string OutputDir = "Assets/Editor/Build/Icons";
        const string OutputPath = "Assets/Editor/Build/Icons/AppIcon_1024.png";

        // Match the in-game neon palette
        static readonly Color32 BgTop    = new Color32(8,   10, 32,  255);
        static readonly Color32 BgBottom = new Color32(40,  6,  56,  255);
        static readonly Color32 GlowCore = new Color32(255, 240, 200, 255);
        static readonly Color32 GlowEdge = new Color32(255, 80,  120, 0);
        static readonly Color32 PlayerColor = new Color32(80, 230, 255, 255);
        static readonly Color32 OutlineDark = new Color32(0,  0,   0,  255);

        [MenuItem("LoneFighter/Build/Generate App Icon")]
        public static void Generate()
        {
            Directory.CreateDirectory(OutputDir);
            var pixels = new Color32[Size * Size];

            // 1. Vertical gradient background
            for (int y = 0; y < Size; y++)
            {
                float t = y / (float)(Size - 1);
                var c = LerpColor32(BgTop, BgBottom, t);
                int rowStart = y * Size;
                for (int x = 0; x < Size; x++) pixels[rowStart + x] = c;
            }

            // 2. Radial glow behind the player — soft additive halo
            int cx = Size / 2;
            int cy = (int)(Size * 0.56f);
            float glowRadius = Size * 0.42f;
            for (int y = 0; y < Size; y++)
            {
                for (int x = 0; x < Size; x++)
                {
                    float dx = x - cx;
                    float dy = y - cy;
                    float d = Mathf.Sqrt(dx * dx + dy * dy);
                    float t = Mathf.Clamp01(1f - d / glowRadius);
                    // Bias toward core for a stronger center
                    t = t * t;
                    if (t > 0f)
                    {
                        var glow = LerpColor32(GlowEdge, GlowCore, t);
                        int idx = y * Size + x;
                        pixels[idx] = AdditiveBlend(pixels[idx], glow, t);
                    }
                }
            }

            // 3. Player silhouette — large filled circle with cyan tint + dark outline
            int playerRadius = (int)(Size * 0.18f);
            int outlineThickness = 14;
            DrawFilledCircle(pixels, cx, cy, playerRadius, PlayerColor);
            DrawCircleOutline(pixels, cx, cy, playerRadius, outlineThickness, OutlineDark);

            // 4. Forward-facing notch (visual identity — same as in-game player sprite)
            int notchSize = (int)(playerRadius * 0.32f);
            int notchCx = cx;
            int notchCy = cy + (int)(playerRadius * 0.55f);
            DrawFilledCircle(pixels, notchCx, notchCy, notchSize, new Color32(255, 255, 255, 255));

            // 5. Title text marker — a stylized "LF" monogram below the player.
            //    Drawn as two small filled rounded blocks to read at any size.
            DrawLetterL(pixels, (int)(Size * 0.38f), (int)(Size * 0.16f), (int)(Size * 0.12f));
            DrawLetterF(pixels, (int)(Size * 0.52f), (int)(Size * 0.16f), (int)(Size * 0.12f));

            // Encode as PNG (no alpha — Apple rejects transparent icons)
            var tex = new Texture2D(Size, Size, TextureFormat.RGBA32, false);
            tex.SetPixels32(pixels);
            tex.Apply();
            File.WriteAllBytes(OutputPath, tex.EncodeToPNG());
            Object.DestroyImmediate(tex);

            AssetDatabase.ImportAsset(OutputPath);

            // Configure the imported texture
            var importer = AssetImporter.GetAtPath(OutputPath) as TextureImporter;
            if (importer != null)
            {
                importer.textureType = TextureImporterType.Default;
                importer.alphaIsTransparency = false;
                importer.alphaSource = TextureImporterAlphaSource.None;
                importer.mipmapEnabled = false;
                importer.npotScale = TextureImporterNPOTScale.None;
                importer.isReadable = true;
                importer.SaveAndReimport();
            }

            // Assign as iOS icon
            var iconTex = AssetDatabase.LoadAssetAtPath<Texture2D>(OutputPath);
            if (iconTex != null)
            {
                Texture2D[] icons = new[] { iconTex };
                PlayerSettings.SetIconsForTargetGroup(BuildTargetGroup.iOS, icons);
                Debug.Log($"[iOS] App icon generated and assigned: {OutputPath}");
            }
            else
            {
                Debug.LogError("[iOS] Icon imported but couldn't be assigned. " +
                               "Assign manually in Project Settings > Player > iOS > Icon.");
            }
        }

        // ------ drawing primitives (no AA — same crisp style as in-game) ------

        static void DrawFilledCircle(Color32[] pixels, int cx, int cy, int r, Color32 color)
        {
            int r2 = r * r;
            for (int y = -r; y <= r; y++)
            {
                int yy = cy + y;
                if (yy < 0 || yy >= Size) continue;
                for (int x = -r; x <= r; x++)
                {
                    int xx = cx + x;
                    if (xx < 0 || xx >= Size) continue;
                    if (x * x + y * y <= r2) pixels[yy * Size + xx] = color;
                }
            }
        }

        static void DrawCircleOutline(Color32[] pixels, int cx, int cy, int r, int thickness, Color32 color)
        {
            int outer2 = r * r;
            int inner = r - thickness;
            int inner2 = inner * inner;
            for (int y = -r; y <= r; y++)
            {
                int yy = cy + y;
                if (yy < 0 || yy >= Size) continue;
                for (int x = -r; x <= r; x++)
                {
                    int xx = cx + x;
                    if (xx < 0 || xx >= Size) continue;
                    int d2 = x * x + y * y;
                    if (d2 <= outer2 && d2 >= inner2) pixels[yy * Size + xx] = color;
                }
            }
        }

        static void DrawFilledRect(Color32[] pixels, int x0, int y0, int w, int h, Color32 color)
        {
            for (int y = 0; y < h; y++)
            {
                int yy = y0 + y;
                if (yy < 0 || yy >= Size) continue;
                for (int x = 0; x < w; x++)
                {
                    int xx = x0 + x;
                    if (xx < 0 || xx >= Size) continue;
                    pixels[yy * Size + xx] = color;
                }
            }
        }

        static void DrawLetterL(Color32[] pixels, int x, int y, int h)
        {
            int w = h / 4;
            int armW = h / 2;
            DrawFilledRect(pixels, x, y, w, h, new Color32(255, 255, 255, 255));
            DrawFilledRect(pixels, x, y, armW, w, new Color32(255, 255, 255, 255));
        }

        static void DrawLetterF(Color32[] pixels, int x, int y, int h)
        {
            int w = h / 4;
            int armW = h / 2;
            DrawFilledRect(pixels, x, y, w, h, new Color32(255, 255, 255, 255));
            DrawFilledRect(pixels, x, y + h - w, armW, w, new Color32(255, 255, 255, 255));
            DrawFilledRect(pixels, x, y + (h / 2) - (w / 2), (int)(armW * 0.75f), w, new Color32(255, 255, 255, 255));
        }

        static Color32 LerpColor32(Color32 a, Color32 b, float t)
        {
            t = Mathf.Clamp01(t);
            return new Color32(
                (byte)(a.r + (b.r - a.r) * t),
                (byte)(a.g + (b.g - a.g) * t),
                (byte)(a.b + (b.b - a.b) * t),
                (byte)(a.a + (b.a - a.a) * t));
        }

        static Color32 AdditiveBlend(Color32 dst, Color32 src, float weight)
        {
            float r = dst.r / 255f + (src.r / 255f) * weight;
            float g = dst.g / 255f + (src.g / 255f) * weight;
            float b = dst.b / 255f + (src.b / 255f) * weight;
            return new Color32(
                (byte)(Mathf.Clamp01(r) * 255f),
                (byte)(Mathf.Clamp01(g) * 255f),
                (byte)(Mathf.Clamp01(b) * 255f),
                255);
        }
    }
}
#endif
